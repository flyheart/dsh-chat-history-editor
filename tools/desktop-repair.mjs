#!/usr/bin/env node
/**
 * Repair this plugin's install inside a DSH Desktop web profile.
 *
 * Why this exists: the first Desktop launch can import a CLI Harness home
 * (`~/.dsh`). For third-party plugins the import copies only `package.json`
 * and relies on a later profile migration to reinstall the package. If that
 * migration is deferred (for example because another imported bundle has no
 * installed manifest), the stub stays and Desktop's preflight cannot read the
 * bundle's `cordis.patch.yml`:
 *
 *   normal Profile startup inputs are invalid: failed to prepare profile bundle
 *     dsh-chat-history-editor
 *
 * Desktop then boots Safe Mode and records the plugin as disabled. This tool
 * materializes the package body from this checkout, clears the disable marker,
 * and drops the generated disabled-plugins overlay when it names this plugin.
 *
 * It only touches:
 *   - <dshHome>/profiles/<profile>/node_modules/<package>/
 *   - <dshHome>/profiles/<profile>/.dsh-market/state.json
 *   - <dshHome>/desktop-disabled-plugins.patch.yml (generated by Desktop)
 *
 * Usage:
 *   node tools/desktop-repair.mjs [--home <dshHome>] [--profile web] [--dry-run]
 *
 * The DSH home defaults to $DSH_HOME, then to the Desktop app's harness home
 * for this platform. Restart DSH Desktop afterwards (quit Safe Mode if the
 * app is currently recovering).
 */

import { readdir, readFile, rm, stat, writeFile, mkdir, copyFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/** This package's checked-out root directory. */
const REPO = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

/** Files that must exist for Desktop preflight to accept the bundle. */
const REQUIRED = ['package.json', 'index.js', 'client.js', 'history-ops.js', 'cordis.patch.yml']

/** Bundle entry ids declared by a patch file, used to spot a stale overlay. */
function patchRowIds(text) {
  const ids = []
  for (const match of text.matchAll(/^\s*-\s*id:\s*['"]?([A-Za-z0-9._:-]+)['"]?\s*$/gmu)) ids.push(match[1])
  return ids
}

/** Escape one regex literal chunk. */
function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&')
}

/** Platform default for the Desktop app's Harness home. */
function defaultDesktopHome() {
  if (process.platform === 'darwin') {
    return path.join(os.homedir(), 'Library', 'Application Support', 'dsh-desktop', 'harness')
  }
  if (process.platform === 'win32') {
    const roaming = process.env.APPDATA ?? path.join(os.homedir(), 'AppData', 'Roaming')
    return path.join(roaming, 'dsh-desktop', 'harness')
  }
  const config = process.env.XDG_CONFIG_HOME ?? path.join(os.homedir(), '.config')
  return path.join(config, 'dsh-desktop', 'harness')
}

/** @returns {{ home: string, profile: string, dryRun: boolean, help: boolean }} */
function parseArguments(argv) {
  const options = {
    home: process.env.DSH_HOME ?? defaultDesktopHome(),
    profile: 'web',
    dryRun: false,
    help: false
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--home') {
      options.home = argv[++index] ?? options.home
    } else if (argument === '--profile') {
      options.profile = argv[++index] ?? options.profile
    } else if (argument === '--dry-run') {
      options.dryRun = true
    } else if (argument === '--help' || argument === '-h') {
      options.help = true
    } else {
      throw new Error(`unknown argument: ${argument}`)
    }
  }
  if (!/^[A-Za-z0-9._-]+$/u.test(options.profile)) throw new Error(`invalid profile name: ${options.profile}`)
  return options
}

/** Expand the package manifest's `files` list into existing relative paths. */
async function packageFiles(root, manifest) {
  /** @type {Set<string>} */
  const wanted = new Set(['package.json'])
  for (const pattern of Array.isArray(manifest.files) ? manifest.files : []) {
    if (typeof pattern !== 'string' || pattern === '' || path.isAbsolute(pattern) || pattern.split('/').includes('..')) continue
    if (!pattern.includes('*')) {
      wanted.add(pattern.replace(/\/+$/u, ''))
      continue
    }
    const segments = pattern.split('/')
    const wildcard = segments.findIndex((segment) => segment.includes('*'))
    const rest = segments.slice(wildcard + 1)
    if (wildcard < 0 || rest.length > 0) continue
    const directory = segments.slice(0, wildcard).join('/') || '.'
    const expression = new RegExp(`^${segments[wildcard].split('*').map(escapeRegExp).join('.*')}$`, 'u')
    let names = []
    try {
      names = await readdir(path.join(root, directory))
    } catch {
      continue
    }
    for (const name of names) {
      if (expression.test(name)) wanted.add(path.posix.join(directory, name))
    }
  }
  for (const always of ['LICENSE', 'README.md']) wanted.add(always)
  const present = []
  for (const relative of [...wanted].sort()) {
    try {
      if ((await stat(path.join(root, relative))).isFile()) present.push(relative)
    } catch {
      // Optional entries may be absent from a source checkout.
    }
  }
  return present
}

/** Read JSON, returning undefined when the file is absent or malformed. */
async function readJsonIfPresent(file) {
  try {
    return JSON.parse(await readFile(file, 'utf8'))
  } catch {
    return undefined
  }
}

async function exists(file) {
  try {
    await stat(file)
    return true
  } catch {
    return false
  }
}

/** Refuse paths outside the resolved DSH home before any write or delete. */
function insideHome(home, target) {
  const relative = path.relative(path.resolve(home), path.resolve(target))
  return relative !== '' && !relative.startsWith('..') && !path.isAbsolute(relative)
}

async function main() {
  const options = parseArguments(process.argv.slice(2))
  if (options.help) {
    console.log('Usage: node tools/desktop-repair.mjs [--home <dshHome>] [--profile web] [--dry-run]')
    return
  }

  const home = path.resolve(options.home)
  const profileDirectory = path.join(home, 'profiles', options.profile)
  const profileManifestPath = path.join(profileDirectory, 'package.json')
  const repositoryManifest = JSON.parse(await readFile(path.join(REPO, 'package.json'), 'utf8'))
  const name = repositoryManifest.name
  if (typeof name !== 'string' || name === '') throw new Error('the checkout has no package name')

  if (!(await exists(profileManifestPath))) {
    throw new Error(
      `no DSH Desktop profile found at ${profileDirectory}\n` +
        'Pass --home <dshHome> (the Desktop app uses ~/Library/Application Support/dsh-desktop/harness on macOS).'
    )
  }

  const profileManifest = JSON.parse(await readFile(profileManifestPath, 'utf8'))
  const bundles = Array.isArray(profileManifest.dsh?.profile?.bundles) ? profileManifest.dsh.profile.bundles : []
  const listed = bundles.includes(name)
  const declared = profileManifest.dependencies?.[name]

  const packageDirectory = path.join(profileDirectory, 'node_modules', ...name.split('/'))
  const missing = []
  for (const relative of REQUIRED) {
    if (!(await exists(path.join(packageDirectory, relative)))) missing.push(relative)
  }
  const stubOnly = missing.length === REQUIRED.length - 1 && (await exists(path.join(packageDirectory, 'package.json')))
  const installed = missing.length === 0

  const files = await packageFiles(REPO, repositoryManifest)
  if (files.length === 0) throw new Error(`no package files resolved from ${REPO}`)

  const marketStatePath = path.join(profileDirectory, '.dsh-market', 'state.json')
  const marketState = await readJsonIfPresent(marketStatePath)
  const disabled = Array.isArray(marketState?.disabled) ? marketState.disabled : []
  const marketDisabled = disabled.includes(name)

  const overlayPath = path.join(home, 'desktop-disabled-plugins.patch.yml')
  let overlayNamesPlugin = false
  if (await exists(overlayPath)) {
    const patchIds = new Set(patchRowIds(await readFile(path.join(packageDirectory, 'cordis.patch.yml'), 'utf8').catch(() => '')))
    const overlayText = await readFile(overlayPath, 'utf8')
    overlayNamesPlugin = overlayText.includes(name) || [...patchIds].some((id) => overlayText.includes(`id: ${id}`) || overlayText.includes(`id: "${id}"`))
  }

  console.log(`Desktop Harness home: ${home}`)
  console.log(`Profile:              ${options.profile}`)
  console.log(`Plugin:               ${name}@${String(repositoryManifest.version ?? '?')} (this checkout)`)
  console.log(`Declared dependency:  ${declared === undefined ? '(none)' : String(declared)}`)
  console.log(`Bundle selection:     ${listed ? 'listed in dsh.profile.bundles' : 'NOT listed (install from Plugins to enable it)'}`)
  if (declared !== undefined && declared !== repositoryManifest.version) {
    console.log(`Note:                 the checkout version differs from the recorded dependency spec; registry installs will keep using ${String(declared)}`)
  }
  if (installed) {
    console.log('Installed copy:       complete')
  } else if (stubOnly) {
    console.log('Installed copy:       manifest-only stub (the failing state)')
  } else {
    console.log(`Installed copy:       incomplete (missing ${missing.join(', ')})`)
  }
  console.log(`Market disable list:  ${marketDisabled ? 'contains this plugin' : 'clean'}`)
  console.log(`Disabled overlay:     ${overlayNamesPlugin ? 'disables this plugin' : 'not present / unrelated'}`)
  console.log('')

  const actions = []
  if (!installed) actions.push(`install ${files.length} package file(s) into ${packageDirectory}`)
  if (marketDisabled) actions.push(`remove "${name}" from ${marketStatePath}`)
  if (overlayNamesPlugin) actions.push(`delete the generated overlay ${overlayPath}`)

  if (actions.length === 0) {
    console.log('Nothing to repair. If Desktop still boots Safe Mode, check the app log for this plugin.')
    return
  }

  console.log('Plan:')
  for (const action of actions) console.log(`  - ${action}`)
  if (options.dryRun) {
    console.log('\nDry run: no changes written.')
    return
  }
  if (!insideHome(home, packageDirectory)) throw new Error('refusing to write outside the DSH home')
  if (!insideHome(home, marketStatePath)) throw new Error('refusing to write outside the DSH home')

  if (!installed) {
    await rm(packageDirectory, { recursive: true, force: true })
    await mkdir(packageDirectory, { recursive: true })
    for (const relative of files) {
      const destination = path.join(packageDirectory, relative)
      await mkdir(path.dirname(destination), { recursive: true })
      await copyFile(path.join(REPO, relative), destination)
    }
  }
  if (marketDisabled) {
    const next = {
      ...marketState,
      disabled: disabled.filter((entry) => entry !== name)
    }
    await mkdir(path.dirname(marketStatePath), { recursive: true })
    await writeFile(marketStatePath, `${JSON.stringify(next)}\n`, 'utf8')
  }
  if (overlayNamesPlugin) await rm(overlayPath, { force: true })

  console.log('\nRepaired. Quit Safe Mode (or restart DSH Desktop) and open a conversation;')
  console.log('the view ring should show History beside Chat and Trajectory.')
}

main().catch((error) => {
  console.error(`desktop-repair: ${error instanceof Error ? error.message : String(error)}`)
  process.exitCode = 1
})
